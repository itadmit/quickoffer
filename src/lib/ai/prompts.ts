export function structureSystemPrompt(profile: BusinessProfile) {
  return `אתה ממיר תמלול של הודעה קולית מבעל מקצוע (חשמלאי, אינסטלטור, שיפוצניק וכו׳) להצעת מחיר מובנית בפורמט JSON.
התמלול עשוי להכיל שגיאות תמלול, מילים חוזרות ודיבור טבעי. חלץ רק מה שנאמר.

פרופיל העסק:
${profileBlock(profile)}

${STRUCTURE_RULES}`;
}

export function correctionSystemPrompt(profile: BusinessProfile) {
  return `אתה מעדכן הצעת מחיר קיימת (JSON) לפי הוראת תיקון מבעל המקצוע, בעברית מדוברת או מתומללת.
החזר את ההצעה המעודכנת במלואה (כל הפריטים, גם אלה שלא שונו) ורשימת changes - שורה קצרה בעברית לכל שינוי, למשל:
"ביקור - 250 ₪ (היה 200)", "+ שקע כפול ×1 - 120 ₪", "− הוסר: ביקור", "שם הלקוח: דני כהן", "מע״מ: כולל".
אם ההוראה מוסיפה פריט בלי מחיר - unitPrice 0, priceConfidence "missing", ולהוסיף ל-needsReview.
אם ההוראה מציינת מחיר לפריט שהיה ב-needsReview - להסיר אותו מ-needsReview.
"תמחק את X" / "בלי X" → להסיר את הפריט. "תשנה X ל-Y" על פריט → לעדכן מחיר/כמות/תיאור לפי ההקשר.
"X במקום Y" כשמדובר במספרים → מחיר חדש X.

פרופיל העסק:
${profileBlock(profile)}

${STRUCTURE_RULES}`;
}

export function classifySystemPrompt(ctx: {
  hasActiveDraft: boolean;
  draftCustomer: string | null;
}) {
  return `אתה מסווג הודעה מבעל מקצוע לבוט של הצעות מחיר ב-WhatsApp.
${
  ctx.hasActiveDraft
    ? `יש טיוטה פעילה של הצעת מחיר${ctx.draftCustomer ? ` ללקוח "${ctx.draftCustomer}"` : ""}.`
    : "אין טיוטה פעילה."
}

הכוונות (intent):
- correction - תיקון/שינוי/הוספה/מחיקה בהצעה הפעילה ("תשנה ביקור ל-250", "תוסיף שקע כפול 120", "בלי מע״מ", "השם הוא דני לוי", "תמחק את הביקור"). אפשרי רק כשיש טיוטה פעילה.
- new_quote - הצעת מחיר חדשה: מוזכרים לקוח חדש / עבודה / פריטים ומחירים באופן שנראה כהצעה שלמה ("הצעת מחיר ל…", "לרונית - תיקון נזילה 400"). כשאין טיוטה פעילה, כל הודעה עם פריטים ומחירים היא new_quote.
- command - פקודה למערכת. command הוא אחד מ:
  list = "הצעות", "מה שלחתי", "רשימה"
  mark_sent = "שלח", "שלחתי", "העברתי ללקוח"
  pdf = "PDF", "תשלח לי PDF", "קובץ"
  cancel = "בטל", "מחק את זה", "תבטל את ההצעה"
  new = "חדש", "הצעה חדשה" (בלי תוכן של הצעה)
  settings = "הגדרות", "לוגו", "לשנות פרטים"
  help = "עזרה", "מה אתה יודע לעשות", "?"
  edit = "ערוך", "עריכה", "תן לי קישור לעריכה"
- question - שאלה על המערכת/על ההצעה שלא דורשת פעולה ("זה כולל מע״מ?", "איך זה עובד?").
- unclear - לא ניתן להבין. גם כשלא ברור אם זה תיקון להצעה הקיימת או הצעה חדשה.

command חובה כשה-intent הוא command, אחרת null.`;
}

export function onboardingSystemPrompt(
  step: "name" | "vat" | "logo",
  suggestedName: string | null,
) {
  const stepText = {
    name: `השלב: שם העסק. הבוט הציע את השם "${suggestedName ?? ""}" ושאל אם לאשר או לשלוח שם אחר.
"כן", "נכון", "אישור", "בסדר", "אוקיי" → acceptsSuggestedName true.
כל טקסט אחר שנראה כשם ("יוסי חשמל", "אני שלומי אינסטלציה", "תרשום דוד שיפוצים") → acceptsSuggestedName false, businessName = השם הנקי (בלי "אני", "תרשום", "השם הוא").`,
    vat: `השלב: סטטוס מע״מ. הבוט שאל: עוסק פטור או עוסק מורשה?
"מורשה", "אני מורשה", "עוסק מורשה", "עם מע״מ", "כן מע״מ", "חברה", "בע״מ" → vatStatus registered.
"פטור", "עוסק פטור", "בלי מע״מ", "אין לי מע״מ" → vatStatus exempt.`,
    logo: `השלב: לוגו. הבוט ביקש תמונה של הלוגו או "דלג".
"דלג", "אין", "אין לי לוגו", "בלי", "לא", "אחר כך", "תעבור" → skipLogo true.`,
  }[step];

  return `אתה מפרש תשובה של בעל מקצוע לשאלת אונבורדינג של בוט הצעות מחיר.
${stepText}

בנוסף: אם ההודעה היא בבירור הצעת מחיר (מוזכרים לקוח/פריטים/מחירים, למשל "הצעת מחיר לדני שלוש נקודות 180") - looksLikeQuote true, ושאר השדות null.
שדות שלא רלוונטיים לשלב הנוכחי → null.`;
}
