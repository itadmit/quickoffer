/** Vocabulary hints (§7.1) - joined into the Whisper prompt. Legacy export kept for callers. */
export const TRANSCRIPTION_HINTS = [TRANSCRIPTION_PROMPT];

export function transcriptionPrompt(hints: string[]): string {
  const business = hints.join(" ");
  const extra = Object.entries(TRADE_VOCAB)
    .filter(([k]) => business.includes(k))
    .map(([, v]) => v)
    .join(", ");
  return [TRANSCRIPTION_PROMPT, business, extra].filter(Boolean).join(" ");
}

// ------------------------------------------------------------------ shared

function profileBlock(p: BusinessProfile) {
  return [
    `שם העסק: ${p.businessName ?? "לא ידוע"}`,
    `סטטוס מע״מ: ${p.vatStatus === "exempt" ? "עוסק פטור (אין מע״מ בכלל - vatIncluded לא רלוונטי, החזר null)" : "עוסק מורשה (מע״מ 18%)"}`,
    `תנאי תשלום ברירת מחדל: ${p.defaultPaymentTerms ?? "לא הוגדר"}`,
    `תוקף ברירת מחדל: ${p.defaultValidDays} יום`,
  ].join("\n");
}

/**
 * Work this professional has already priced. Only the wording is shared with
 * the model - prices are filled deterministically in lib/quotes/price-book.ts,
 * which keeps this block short (the Groq free tier is 8k tokens/minute).
 */
function catalogBlock(catalog: string[]): string {
  if (!catalog.length) return "";
  return `
## עבודות שבעל המקצוע כבר תמחר בעבר
${catalog.join(" · ")}
אם העבודה שנאמרה היא אחת מאלה - נסח אותה **בדיוק** כמו ברשימה, כדי שהניסוח יישאר עקבי בין הצעות. עבודה שלא ברשימה - נסח חופשי לפי הכללים. אל תוסיף פריטים מהרשימה שלא נאמרו, ואל תשאב מהם מחירים.
`.trim();
}

